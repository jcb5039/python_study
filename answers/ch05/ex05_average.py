# 5장 문제 5 정답
#
# 해설:
# - 입력이 두 줄이니까 input()을 두 번 불러요.
# - 첫째 줄은 이름(문자열) 그대로, 둘째 줄은 숫자 세 개 → map(int, ...)
# - 평균 = 합 / 3. / 는 실수를 돌려줘요.
# - {average:.2f} 로 소수점 둘째 자리까지. 90.0 → 90.00
#
# 자주 틀리는 점:
# - (a + b + c) // 3 처럼 몫을 쓰면 소수점 아래가 사라져요.
# - a + b + c / 3 은 c / 3 만 먼저 계산돼요. 괄호가 필요해요.

name = input()
a, b, c = map(int, input().split())
average = (a + b + c) / 3
print(f'{name}의 평균: {average:.2f}')
