# 7장 문제 3 정답
#
# 해설:
# - 위쪽: 1부터 N까지 늘어나요 → range(1, n + 1)
# - 아래쪽: N-1부터 1까지 줄어들어요 → range(n - 1, 0, -1)
#   (끝 번호 0은 포함하지 않으니까 1에서 멈춰요)
# - '*' * i 는 별을 i개 반복한 문자열이에요.
#
# 자주 틀리는 점:
# - 아래쪽을 range(n, 0, -1)로 시작하면 가운데 줄(N개)이 두 번 나와요.
# - N이 1이면 아래쪽 range(0, 0, -1)은 비어 있어서 아무것도 안 나와요. 그래서 따로 처리할 필요 없어요.

n = int(input())
for i in range(1, n + 1):
    print('*' * i)
for i in range(n - 1, 0, -1):
    print('*' * i)
