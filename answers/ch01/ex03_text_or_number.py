# 1장 문제 3 정답
#
# 해설:
# - 1번째 줄: 따옴표 안의 '12 * 3'은 글자라서 계산하지 않고 그대로 보여 줘요.
# - 2번째 줄: 따옴표가 없는 12 * 3은 파이썬이 계산해서 36을 보여 줘요.
# - 3번째 줄: print 안에 쉼표로 여러 개를 넣으면 띄어쓰기 하나를 두고 한 줄에 나와요.
#   '12 * 3 ='(글자) + 띄어쓰기 + 36(계산 결과) → 12 * 3 = 36
#
# 자주 틀리는 점:
# - print('12 * 3 =', 12 * 3)에서 '12 * 3 = '처럼 따옴표 안 끝에 띄어쓰기를 넣으면
#   쉼표가 넣는 띄어쓰기까지 합쳐져서 '=' 뒤에 칸이 두 개가 돼요.

print('12 * 3')
print(12 * 3)
print('12 * 3 =', 12 * 3)
